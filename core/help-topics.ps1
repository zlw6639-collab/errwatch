# core/help-topics.ps1 — 设置里「帮助」页的正文（2026-10-26）
#
# 为什么单独成文件：
#   ① 帮助正文有几千字，塞在设置窗脚本里会把那个文件撑得没法读
#   ② 用户要求「做成目录，选目录再打开相关内容，并且需要详细」——
#      内容按主题组织，这里只放数据，界面逻辑还在 errwatch-settings-ui.ps1
#   ③ 测试能直接 dot-source 本文件检查"每个主题都有内容"（不用起界面）
#
# 写作原则（对着前几版的反馈定的）：
#   · 直说，不绕：用户看不懂"内部枚举值""契约 §十"这类话
#   · 每条主题都独立完整，不要求按顺序读
#   · 能力边界一律照实写（做不到的要说做不到）

$script:EwHelpTopics = [ordered]@{
    '1. 它是什么、能做什么' = @'
一个只看不动的「报错记录员」。

它读 Windows 自己的错误日志和进程退出情况，把技术的东西翻成四句话：
  发生了什么 / 有多可信 / 下一步做什么 / 该找谁

它不做的事（这几条最容易被误解）：
  · 不注入、不挂钩子、不改你的程序
  · 不联网、不上传任何东西（全仓 0 处网络 API，2026-10-25 重扫确认）
  · 不自动重启、不自动结束进程、不自动删文件
  · 不需要管理员权限就能用（只有"崩溃快照布防"那一步需要）

它跟杀毒/优化软件的区别：
  那些会"动手"，它只"记录 + 解释"。你不动，它也不动。
'@

    '2. 主界面怎么看' = @'
列表每一行的意思：
  时间      这条记录的时间
  程序      程序的中文名（括号里是真实 exe 名）
  错误码    崩溃码。0xc0000005 = 读写不属于自己的内存，最常见的那种
  模块      出错时落在哪个 DLL —— 注意它通常不是"这个 DLL 坏了"
  状态      崩溃 / 已恢复 / 进程消失 / 自关（含义见下）
  来源      Windows 日志（系统记的） 或 哨兵观测（我们自己看到的）
  人话      一句话结论

四种状态的区别很重要：
  崩溃      有崩溃证据（Windows 记录了，或者找到了内存快照）
  已恢复    崩了之后程序自己又跑起来了 —— 只说明能用了，原因还没查
  进程消失  进程没了，但没有崩溃证据（可能是你关的、被强杀、或崩了没留记录）
  自关      退出前它是前台窗口、退出码 0，多半是你自己关的

底部「详细信息」怎么用：
  先点开它，再在列表里选一行，下面会给四段 ——
    为什么没了 / 系统记录原文 / 可能的原因 / 你可以这样做
  它默认是收起的（省地方）。展开时如果还没选行，它会告诉你怎么用。

右上角「开始扫描」= 现在去采集一次（约 10 秒）。
打开界面时本来就会自动扫一次，所以平时不用点它。

状态栏里如果写着「只显示了最近 500 条」，点它一下就能加载全部。
（默认只处理最近一批是为了开得快；老记录一直在文件里，没丢。）
'@

    '3. 托盘怎么用' = @'
托盘图标 = 右下角那只会看着的眼睛。

在哪儿：Windows 11 默认把新程序的托盘图标放进隐藏区。
  点任务栏右端的 ^ 展开，把图标拖到外面（或右键设成"始终显示"）就一直看得见。

右键菜单能做什么：
  监视状态        看护（哨兵 + 托盘）是否都在跑
  待处理 (N)      展开成逐条事件，点某条直接去救它
  打开/关闭主界面
  应急救援 / 重新启动看护 / 退出

气泡什么时候弹：
  由「设置 → 弹窗设置」决定，默认只弹有崩溃证据或反复崩溃的。
  「全部不弹窗」只是不打扰你 —— 记录照常，不等于关掉看护。

从托盘退出之后：
  再双击桌面「报错看护」会自动把托盘拉回来。
  双击的意义是"我要用这套东西"，所以三条腿（界面 / 哨兵 / 托盘）都会被带起来。

只会有这一个图标：整机唯一（2026-10-26 修）。
  如果哪天看到两个，那就是 bug，告诉我。
'@

    '4. 设置各项是什么意思' = @'
设置分七页，每页开头都有一句话说明。这里给个总览：

救援目录
  给某个程序追加「去哪里找恢复文件」。
  多数人不用动 —— 内置名单已经覆盖 CAD / Office / 记事本 / VS Code 等的默认位置。
  什么时候用：你把文件存在特殊地方，自动救援没找到。
  用法：填程序名（如 winword）→ 选目录 → 点「添加」。

监视目标
  「内置」是随包分发的默认名单；「我加的」是你自己加的。
  ★ 加了之后 10 秒内生效，不用重启看护（2026-10-26 修好的）。
  只有名单里的程序退出才会被记录；正常退出不会打扰你。

弹窗设置
  四档：全部弹 / 只弹重大（默认）/ 只弹白名单 / 全部不弹。
  超时提醒单独可控（要不要弹 + 多久算过期）。
  ★ 只影响气泡，不影响记录、不影响待处理。

时限与兜底
  诊断时限 = 一次取证最多花多久（到点就停，保留已有证据）
  兜底时限 = 多久没处理就升级提示（只会提示，绝不自动动手）

存储与清理
  记录保留几天、副本/快照保留几天、副本目录设在哪。
  ★ 程序不会自己删文件；清理要你亲手点。

工具
  看护健康、重启看护、打开最新报告、打开证据目录、看完的感受。

关于
  配置文件位置、两个时限的含义、本版的行为承诺。
'@

    '5. 监视范围（为什么有的程序没被记录）' = @'
它盯的是这四类的并集：
  ① 内置名单（随包分发：CAD / Office / IDE / 记事本 / 串流工具 等）
  ② 当前有窗口的程序（动态）
  ③ 崩过一次的程序（从历史里学，动态）
  ④ 你在「设置 → 监视目标」里手动加的

所以「我的某个程序崩了但没记录」通常是这三个原因：
  · 它是后台进程、以前没崩过、也不在名单里
    → 要等它崩过一次才被学到，或者你现在手动加进「监视目标」
  · 它崩的时候看护没在跑（去「工具 → 看护健康」看哨兵和托盘）
  · 它其实没崩，是正常退出（退出码 0 且在前台 → 判"自关"，不打扰你）

一个诚实的边界：
  名单里写了名字，不等于本机真的装了这个程序（没装的不触发，装了才生效）。
  反过来，装了的程序如果 exe 名和名单不一致，按名字匹配就会漏 ——
  这类坑记录在案的就有好几条（比如带空格的 "DSH Desktop"）。
'@

    '6. 崩溃快照是什么' = @'
崩溃快照 = 崩溃那一刻程序内存的副本（迷你转储，每份几 MB）。

为什么有用：程序崩的时候，它自己在内存里"说了什么、卡在哪个模块"都在里面。
  把这个文件给懂电脑的人，比口头描述现象有用得多。

怎么开：默认关闭。开启要写系统级注册表，需要一次管理员权限。
  开启后，被布防的程序崩溃时会自动在 C:\ProgramData\errwatch\dumps 留一份。

风险（必须知道）：
  内存转储可能包含你当时正在处理的内容 —— 文档片段、剪贴板、聊天文字、登录态。
  所以：默认不开是有意的；别在含敏感资料的机器上开；
  文件只在本机、不会上传；删不删由你决定。

不保证抓得到：
  杀软 / 反作弊 / 程序自带的崩溃处理器可能抢先接管
  （2026-10-25 实测：进程内的 handler 会赢）。
  所以「布防了」≠「一定有快照」—— 详情区那句"可能被自带处理器抢先接管"是实测结论，不是免责话术。
'@

    '7. 哪些操作会动你的文件' = @'
只有两个按钮会碰磁盘上的东西，其余全是只读：

「开始应急救援」→ 只读 + 复制
  扫描该程序留下的恢复文件（.sv$ / .asd / .tmp 等），找到后复制一份给你，
  绝不修改、不覆盖原件。
  复制过程：临时名 → 比长度 → 比 SHA256 → 才确认成功。

「一键删除过时…」→ 真的删
  但只删你自己点的那批，而且只在有归属标记的目录里删。
  归属标记（.errwatch-copydir）是你选定副本目录时写入的 ——
  所以即使你误把「文档」设成副本目录，它也只会动它自己放进去的文件。
  这条是 2026-10-25 挖出的灾难级误删漏洞的修法：
  之前会把你 40 天没动的年终总结也列进"可删除"清单。

其余全部只读：
  刷新 / 生成修复 / 看报告 / 打开证据目录 / 按程序统计。

没有"后台偷偷删东西"这种行为。
'@

    '8. 出问题该查哪儿' = @'
按这个顺序，从轻到重：

1. 主界面底部状态栏 —— 刚才的扫描/加载结果、加载了多少条
2. 设置 → 工具 → 看护健康 —— 哨兵和托盘是否都在跑，
   还能看到「上次托盘退出」的时间和原因
3. errwatch-doctor.ps1 —— 一条命令做完整自检：
   响应链三段（计划任务 / 启动文件夹 / 心跳）、恢复机会、托盘状态
4. 最新报告 report-*.md —— 给懂电脑的人看的那份，含逐条明细
5. sentinel-error.log —— 看护自己的错误（一般人不用看）

常见现象对应：
  · 界面正常但没有新记录   → 哨兵没在跑（查第 2 项）
  · 有记录但从不弹气泡     → 托盘没在跑，或弹窗设置选了不弹
  · 气泡太多太吵           → 弹窗设置改成「只弹重大崩溃」
  · 双击快捷方式没界面     → 看 ui-crash.log；也可能有残留的界面进程占着
  · 托盘图标找不到         → Win11 把它藏在 ^ 里了（见"托盘怎么用"）
'@

    '9. 它做不到什么（诚实边界）' = @'
这一节故意写得直白 —— 免得你对它有不存在的期待：

· 崩溃快照不保证抓到：杀软 / 反作弊 / 自带崩溃处理器可能先接管。
· 只在监视范围内：新装的后台程序要崩过一次才被学到。
· 「已恢复」不等于问题解决：只说明程序能用了，崩溃原因还没查。
  反复出现（6 小时内 ≥3 次）会专门标出来提醒你。
· 看不到"为什么"时会明说看不到：没有崩溃记录就写「没有崩溃证据」，
  不会编一个原因给你。
· 模块名通常不是罪魁祸首：崩溃落在 KERNELBASE.dll 只说明异常从那儿抛出来，
  不代表 KERNELBASE 坏了。
· 同一程序 24 小时内只留一条待处理：折叠是为了不刷屏；
  完整事实都在 sentinel-events.jsonl 里，一条不少。
· 多实例应用（浏览器 / DSH 这类）不自动归位：分不清是哪个实例恢复了。
· 默认只处理最近 500 条事件：为了开得快。点状态栏可以加载全部。
'@

    '10. 卸载与残留' = @'
一键卸载：双击 ③ 卸载报错看护.cmd（默认只预览，你确认了才动）

它处理七处：
  ① 停进程（哨兵 / 托盘 / 界面）—— 按进程名 + 命令行精确匹配，不误杀编辑器
  ② 删两个启动项（启动文件夹里的 vbs）
  ③ 计划任务（如果注册过）
  ④ 桌面快捷方式
  ⑤ 运行期状态文件（待处理 / 已处理记录 / 事件记录等 14 个）
  ⑤.5 撤销崩溃快照布防（系统级注册表里那批程序的 LocalDumps 项）——
      判据是 DumpFolder 指向 errwatch，不按名字猜，免得误删别的软件的布防
  ⑤.6 崩溃快照文件（默认保留；要删加 -RemoveDumps）
  ⑥ 用户数据默认保留（历史记录 / 报告 / 设置）—— 除非你明确要删

卸载不干净会怎样：
  程序删了、注册表还在替它工作 —— 那些被布防的程序一崩就继续往 dumps 目录写几 MB。
  所以 ⑤.5 是必须的（这正是外部审计挖出的真缺口）。
'@
